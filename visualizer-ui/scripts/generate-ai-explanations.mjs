/*
 * Pre-generate the AI-vis lesson explanations with Gemini, once.
 *
 * Reads GEMINI_API_KEY + GEMINI_MODEL from .env.local and the lesson context in
 * scripts/aiExplanationSeed.json, asks Gemini for an explanation + why-it-matters
 * per step, and writes src/data/aiExplanations.ts. Review that file, re-run to
 * regenerate any lesson, and commit it. The study reads the committed file, so
 * it never calls Gemini at runtime.
 *
 * Usage: node scripts/generate-ai-explanations.mjs [linkedlist|stack]
 *   (no arg = all study lessons)
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

function loadEnvLocal() {
  try {
    const text = readFileSync(join(root, ".env.local"), "utf8");
    for (const line of text.split("\n")) {
      const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
      if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  } catch {
    // no .env.local, rely on the real environment
  }
}

loadEnvLocal();

const API_KEY = process.env.GEMINI_API_KEY;
const MODEL = process.env.GEMINI_MODEL || "gemini-flash-latest";
if (!API_KEY || API_KEY === "your-gemini-api-key") {
  console.error("Set GEMINI_API_KEY in .env.local first (see .env.example).");
  process.exit(1);
}

const seed = JSON.parse(readFileSync(join(here, "aiExplanationSeed.json"), "utf8"));
const only = process.argv[2];
const lessonIds = only ? [only] : Object.keys(seed.lessons);

function buildPrompt(lesson, stepIndex) {
  const step = lesson.steps[stepIndex];
  return [
    "You write short tutor explanations for a Java program-execution visualizer used in a study.",
    "Audience: a student who has taken one intro Java course. Plain, concrete, no fluff.",
    "",
    `Lesson: ${lesson.name}`,
    `What the program does: ${lesson.overview}`,
    `Key rule for this lesson: ${lesson.keyRule}`,
    "",
    "Full step order:",
    ...lesson.steps.map((s, i) => `  ${i + 1}. ${s.code}  // ${s.action}`),
    "",
    `Explain THIS step only: step ${stepIndex + 1}, "${step.code}" (${step.action}).`,
    "",
    "Return JSON with exactly two string fields:",
    '  "explanation": what just changed in memory after this line ran (1 to 2 sentences).',
    '  "whyItMatters": the reference/aliasing idea this step teaches (1 sentence).',
    "Refer to variables, objects, and references concretely. Do not restate the code verbatim.",
  ].join("\n");
}

async function generateStep(lesson, stepIndex) {
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent?key=${API_KEY}`;
  const res = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      contents: [{ parts: [{ text: buildPrompt(lesson, stepIndex) }] }],
      generationConfig: {
        temperature: 0.4,
        responseMimeType: "application/json",
      },
    }),
  });
  if (!res.ok) {
    throw new Error(`Gemini ${res.status}: ${await res.text()}`);
  }
  const data = await res.json();
  const text = data?.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!text) throw new Error(`No text in response: ${JSON.stringify(data).slice(0, 300)}`);
  const parsed = JSON.parse(text);
  if (typeof parsed.explanation !== "string" || typeof parsed.whyItMatters !== "string") {
    throw new Error(`Unexpected shape: ${text.slice(0, 300)}`);
  }
  return { explanation: parsed.explanation.trim(), whyItMatters: parsed.whyItMatters.trim() };
}

const result = {};
for (const id of lessonIds) {
  const lesson = seed.lessons[id];
  if (!lesson) {
    console.error(`No seed entry for lesson "${id}".`);
    process.exit(1);
  }
  result[id] = {};
  for (let i = 0; i < lesson.steps.length; i++) {
    process.stdout.write(`generating ${id} step ${i + 1}/${lesson.steps.length}... `);
    result[id][i] = await generateStep(lesson, i);
    console.log("ok");
  }
}

const header = `/*
 * GENERATED by scripts/generate-ai-explanations.mjs. Reviewed before use.
 * Do not edit the data by hand except to fix a specific explanation; re-run the
 * script to regenerate a lesson. See src/data/aiExplanations.ts for the types.
 */
import type { AiStepExplanation } from "@/data/aiExplanations";

export const GENERATED_AI_EXPLANATIONS: Record<string, Record<number, AiStepExplanation>> = ${JSON.stringify(result, null, 2)};
`;

const outPath = join(root, "src", "data", "aiExplanations.generated.ts");
writeFileSync(outPath, header, "utf8");
console.log(`\nWrote ${outPath}. Review it, then it is picked up by aiExplanations.ts.`);
